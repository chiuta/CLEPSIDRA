// CLEPSIDRA: butonul „Testează alarma (3 s)” sună o dată, fără să activeze/modifice alarma reală. Rulare: node tests/test-alarma.test.mjs
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
const require = createRequire(process.env.PW_ROOT || import.meta.url);
const {chromium} = require('playwright');
const FILE = 'file://' + path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'index.html');
let ok = 0, bad = 0;
const check = (n, c, x) => { if (c) { ok++; console.log('  ok   ' + n); } else { bad++; console.log('  FAIL ' + n + (x !== undefined ? '  → ' + JSON.stringify(x) : '')); } };
const b = await chromium.launch({executablePath: process.env.CHROMIUM_PATH || undefined, args: ['--no-sandbox']});
const ctx = await b.newContext({viewport: {width: 900, height: 900}, locale: 'ro-RO'});
await ctx.route(/^https?:/, (r) => r.abort());
const p = await ctx.newPage(); const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
await p.goto(FILE); await p.waitForTimeout(800);
check('buton prezent, text RO', (await p.textContent('#alarmTestBtn')).includes('Testează alarma'));
await p.click('#alarmTestBtn');
check('mesaj de așteptare + buton dezactivat', (await p.textContent('#alarmHint')).includes('3 secunde') && await p.isDisabled('#alarmTestBtn'));
check('bannerul nu apare imediat', await p.isHidden('#alarmBanner'));
await p.waitForSelector('#alarmBanner:not([hidden])', {timeout: 6000});
check('după ~3 s sună (banner vizibil)', true);
await p.click('#dismissBtn'); await p.waitForTimeout(300);
check('după oprire: banner ascuns', await p.isHidden('#alarmBanner'));
check('alarma reală NU a fost activată', await p.evaluate(() => document.getElementById('alarmToggleBtn').textContent !== '' && !document.getElementById('alarmCountdownWrap').classList.contains('open')));
check('buton din nou activ', !(await p.isDisabled('#alarmTestBtn')));
await p.evaluate(() => { document.querySelector('#langSel, select[id*=lang]') && 0; });
check('fără erori', errs.length === 0, errs);
await b.close();
console.log(`\n${ok} reușite, ${bad} eșuate`); process.exit(bad ? 1 : 0);
